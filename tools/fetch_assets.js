// Builds assets: one flat-front photo per color (resized) + Bella's swatch chips, and colors.js.
// Color list (name, code, hex, swatch) comes from each product page's color <select>. The flat-front photo is
// /bella/product/hires/<style><code><v><v>_<n>.jpg; the style may be upper or lower case. Which view <v> is the
// flat front depends on how many photos a color has: hoodie 5; crewneck 5, or 1 when it only has front/back
// flats; long sleeve 5 when it has six photos, else 4.
const fs = require('fs'), path = require('path');
const puppeteer = require('C:/Users/kevsc/Desktop/Claude/hyrox_pdf/node_modules/puppeteer');
const SITE = path.join(__dirname, '..');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
const PRODUCTS = [
  { id: 'hoodie', style: '3719', url: 'https://www.bellacanvas.com/product/3719/Unisex-Sponge-Fleece-Pullover-Hoodie.html' },
  { id: 'crewneck', style: '3945', url: 'https://www.bellacanvas.com/product/3945/Unisex-Sponge-Fleece-Drop-Shoulder-Sweatshirt.html' },
  { id: 'longsleeve', style: '3501CVC', url: 'https://www.bellacanvas.com/product/3501CVC/Unisex-Heather-CVC-Long-Sleeve-Tee.html' },
];
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const get = async u => { const r = await fetch(u, { headers: { 'User-Agent': UA, Referer: 'https://www.bellacanvas.com/' } }); return r.ok && /image/.test(r.headers.get('content-type') || '') ? Buffer.from(await r.arrayBuffer()) : null; };

(async () => {
  const browser = await puppeteer.launch({ headless: 'new' });
  const page = await browser.newPage();
  await page.setUserAgent(UA);
  const resize = async (buf, w, q) => page.evaluate(async (b64, w, q) => {
    const img = new Image(); img.src = 'data:image/jpeg;base64,' + b64; await img.decode();
    const c = document.createElement('canvas'); c.width = w; c.height = Math.round(img.naturalHeight * w / img.naturalWidth);
    c.getContext('2d').drawImage(img, 0, 0, c.width, c.height);
    return c.toDataURL('image/jpeg', q).split(',')[1];
  }, buf.toString('base64'), w, q);
  const out = {}; const missing = [];
  for (const p of PRODUCTS) {
    await page.goto(p.url, { waitUntil: 'networkidle2', timeout: 90000 });
    const colors = await page.evaluate(() => [...document.querySelectorAll('#mainColorSwatchSelect option')].map(o => ({ name: o.textContent.trim(), code: o.value, hex: '#' + (o.dataset.hex || 'cccccc'), swatch: o.dataset.swatch || '' })));
    fs.mkdirSync(path.join(SITE, 'assets', p.id), { recursive: true });
    out[p.id] = [];
    for (const c of colors) {
      const photo = async v => {
        for (const s of [p.style.toLowerCase(), p.style.toUpperCase()]) for (const n of [1, 2, 3]) {
          const b = await get(`https://www.bellacanvas.com/bella/product/hires/${s}${c.code}${v}${v}_${n}.jpg`); if (b) return b;
        }
        return null;
      };
      let buf = null;
      if (p.id === 'hoodie') buf = await photo(5);
      else if (p.id === 'crewneck') buf = (await photo(5)) || (await photo(1));
      else buf = (await photo(6)) ? await photo(5) : await photo(4);
      if (!buf) { missing.push(p.id + ' ' + c.name); continue; }
      const file = `assets/${p.id}/${slug(c.name)}.jpg`;
      fs.writeFileSync(path.join(SITE, file), Buffer.from(await resize(buf, 640, 0.82), 'base64'));
      let sw = '';
      if (c.swatch) { const s = await get(c.swatch); if (s) { sw = `assets/${p.id}/sw-${slug(c.name)}.jpg`; fs.writeFileSync(path.join(SITE, sw), Buffer.from(await resize(s, 60, 0.85), 'base64')); } }
      out[p.id].push({ name: c.name, hex: c.hex, img: file, ...(sw ? { sw } : {}) });
      process.stdout.write('.');
    }
    console.log('\n' + p.id, out[p.id].length);
  }
  fs.writeFileSync(path.join(SITE, 'colors.js'), '// Generated by tools/fetch_assets.js from bellacanvas.com — garment colors, flat-front photos, swatches.\nconst GARMENT_COLORS = ' + JSON.stringify(out, null, 1) + ';\n');
  console.log('missing:', missing.join('; ') || 'none');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
